const { contextBridge, ipcRenderer } = require("electron");
contextBridge.exposeInMainWorld("electronAPI", {
    toggleFullscreen: () => ipcRenderer.invoke("toggle-fullscreen"),
    getFullscreenState: () => ipcRenderer.invoke("get-fullscreen-state"),
    openAnyDesk: () => ipcRenderer.invoke("open-anydesk"),
    getAnyDeskId: () => ipcRenderer.invoke("get-anydesk-id"),
    printReceipt: (data) => ipcRenderer.invoke("print-receipt", data),
    scanMaster: () => ipcRenderer.invoke("scan-master"),
    getStaticMasterIp: () => ipcRenderer.invoke("get-static-master-ip"),
    setStaticMasterIp: (ip) => ipcRenderer.invoke("set-static-master-ip", ip),
    getMemoryInfo: () => ipcRenderer.invoke("get-memory-info"),
    getDiskInfo: () => ipcRenderer.invoke("get-disk-info"),
    getSyncStatus: () => ipcRenderer.invoke("get-sync-status"),
    getLocalIp: () => ipcRenderer.invoke("get-local-ip"),
    checkInternet: () => ipcRenderer.invoke("check-internet"),
    reEvaluateRole: () => ipcRenderer.invoke("re-evaluate-role"),
    onBackendLog: (callback) => ipcRenderer.on("backend-log", (event, ...args) => callback(...args)),
    getSystemPrinters: () => ipcRenderer.invoke("get-system-printers"),
    installNetworkPrinter: (data) => ipcRenderer.invoke("install-network-printer", data),
    scanNetworkPrinters: (data) => ipcRenderer.invoke("scan-network-printers", data),
    pingPrinter: (data) => ipcRenderer.invoke("ping-printer", data),
    getScreens: () => ipcRenderer.invoke("get-screens"),
    toggleCustomerDisplay: (data) => ipcRenderer.invoke("toggle-customer-display", data),
    toggleKitchenDisplay: (data) => ipcRenderer.invoke("toggle-kitchen-display", data),
    quitApp: () => ipcRenderer.invoke("quit-app"),
    getAppVersion: () => ipcRenderer.invoke("get-app-version"),
    installUpdate: () => ipcRenderer.invoke("install-update"),
    openDevToolsDetached: () => ipcRenderer.invoke("open-devtools-detached"),
    getUniposInstance: () => ipcRenderer.invoke("get-unipos-instance"),
    getUpdateState: () => ipcRenderer.invoke("get-update-state"),
    onCheckingForUpdate: (callback) => ipcRenderer.on("checking-for-update", (event) => callback()),
    onUpdateAvailable: (callback) => ipcRenderer.on("update-available", (event, info) => callback(info)),
    onUpdateDownloadProgress: (callback) => ipcRenderer.on("update-download-progress", (event, percent) => callback(percent)),
    onUpdateDownloaded: (callback) => ipcRenderer.on("update-downloaded", (event, info) => callback(info)),
    getAutoUpdateEnabled: () => ipcRenderer.invoke("get-auto-update-enabled"),
    setAutoUpdateEnabled: (enabled) => ipcRenderer.invoke("set-auto-update-enabled", enabled),
    checkForUpdatesNow: () => ipcRenderer.invoke("check-for-updates-now"),
    getGithubReleases: () => ipcRenderer.invoke("get-github-releases"),
    listComPorts: () => ipcRenderer.invoke("list-com-ports"),
});
